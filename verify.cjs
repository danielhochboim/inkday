'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {dayKey, midnight, nextDay, safeEqual} = require('./server.cjs');
new vm.Script(fs.readFileSync(__dirname + '/docs/app.js', 'utf8'));
new vm.Script(fs.readFileSync(__dirname + '/server.cjs', 'utf8'));
assert.equal(dayKey(new Date('2026-10-22T12:00:00Z')), '2026-10-22');
assert.equal(nextDay('2026-12-31'), '2027-01-01');
assert.equal((midnight('2026-03-28') - midnight('2026-03-27')) / 3600000, 23, 'Israel spring DST');
assert.equal((midnight('2026-10-26') - midnight('2026-10-25')) / 3600000, 25, 'Israel autumn DST');
assert.equal(safeEqual('a'.repeat(64), 'a'.repeat(64)), true);
assert.equal(safeEqual('a'.repeat(64), 'b'.repeat(64)), false);
assert.equal(safeEqual('short', 'short'), false);
const html = fs.readFileSync(__dirname + '/docs/index.html', 'utf8');
assert.ok(!html.includes('script.google.com'));
assert.ok(!fs.readFileSync(__dirname + '/docs/app.js', 'utf8').includes('jsonp'));
console.log('PASS: server/frontend syntax, auth comparison, date boundaries, Israel DST, Apps Script removal.');
